/* Run ONLY against an isolated backend database. Creates test records.
   V03_TEST_BASE_URL and V03_ISOLATED_DB=1 are required intentionally. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const baseURL = process.env.V03_TEST_BASE_URL;
if (!baseURL || process.env.V03_ISOLATED_DB !== '1') throw new Error('Specify isolated test server via V03_TEST_BASE_URL and V03_ISOLATED_DB=1');
const output = process.env.V03_ARTIFACT_DIR || '/private/tmp/honjatmal-v03-browser';
fs.mkdirSync(output, { recursive: true });
const results = [];
const passed = name => { results.push(name); console.log(`PASS ${name}`); };
async function visible(locator) { await locator.waitFor({ state: 'visible' }); }
(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.V03_BROWSER_CHANNEL || 'chrome' });
  try {
    // Intentionally use a non-Korean browser timezone to catch accidental local date conversion.
    const context = await browser.newContext({ viewport: { width: 1280, height: 1000 }, timezoneId: 'America/Los_Angeles' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.goto(baseURL);
    await visible(page.getByRole('heading', { name: '나의 기록', exact: true }));
    for (const path of ['posts', 'visits', 'medications']) {
      const response = await context.request.get(`${baseURL}/api/${path}`);
      assert(response.ok());
      assert.equal((await response.json()).length, 0, 'Use a fresh, empty isolated test DB');
    }
    const today = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Seoul', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
    const [year, month, day] = today.split('-').map(Number);
    const token = `V03 브라우저 ${Date.now()}`;
    // These records predate opening the calendar, exercising reuse of existing Post data.
    await page.getByLabel('기록 내용').fill(`${token} 첫 기록`);
    await page.getByRole('button', { name: '기록', exact: true }).click();
    await visible(page.locator('.timeline').getByText(`${token} 첫 기록`, { exact: true }));
    await page.getByLabel('기록 내용').fill(`${token} 두번째 기록`);
    await page.getByRole('button', { name: '기록', exact: true }).click();
    await visible(page.locator('.timeline').getByText(`${token} 두번째 기록`, { exact: true }));
    assert.equal(await page.locator('.timeline .post-content').first().textContent(), `${token} 두번째 기록`);
    passed('1. 기존 본문 전용 Post 작성 및 최신순 타임라인');
    await page.getByRole('button', { name: '달력', exact: true }).click();
    await visible(page.getByRole('region', { name: '기록과 진료 달력' }));
    await page.getByRole('button', { name: '+ 진료 일정', exact: true }).waitFor({ state: 'visible' });
    const todayCell = page.locator('.calendar-day[aria-current="date"]');
    await visible(todayCell.locator('.post-count'));
    assert.equal(await todayCell.locator('.post-count').textContent(), '● 2');
    passed('2–3. 달력 전환 및 기존 Post 서울 날짜 표시');
    await todayCell.click();
    const details = page.getByRole('region', { name: '선택한 날짜의 기록과 진료' });
    await visible(details.getByText(`${token} 첫 기록`, { exact: true }));
    assert.equal(await details.locator('.post-content').first().textContent(), `${token} 첫 기록`);
    assert.match(await details.locator('.post-meta time').first().textContent(), /^\d{2}:\d{2}$/);
    passed('4. 날짜 선택 및 실제 작성 시간·시간순 Post 표시');
    await page.getByRole('button', { name: '이전 달', exact: true }).click();
    await visible(page.getByRole('heading', { name: `${month === 1 ? year - 1 : year}년 ${month === 1 ? 12 : month - 1}월`, exact: true }));
    await page.getByRole('button', { name: '다음 달', exact: true }).click();
    await visible(page.getByRole('heading', { name: `${year}년 ${month}월`, exact: true }));
    await page.getByRole('button', { name: '오늘', exact: true }).click();
    assert.equal(await todayCell.getAttribute('aria-pressed'), 'true');
    passed('5. 이전/다음 달 및 오늘 이동');
    await page.getByRole('button', { name: '+ 진료 일정', exact: true }).click();
    assert.equal(await page.getByLabel('날짜', { exact: true }).inputValue(), today);
    assert.equal(await page.getByLabel('제목', { exact: true }).inputValue(), '병원 진료');
    await page.getByLabel('시간 (서울)').fill('15:30');
    await page.getByLabel('메모 (선택)', { exact: true }).fill('검증용 진료 메모');
    await page.getByRole('button', { name: '진료 저장', exact: true }).click();
    await visible(todayCell.locator('.visit-marker'));
    await todayCell.click();
    await visible(details.getByText('병원 진료', { exact: true }));
    assert.equal(await details.locator('.visit-heading time').textContent(), '15:30');
    await visible(details.getByText('검증용 진료 메모', { exact: true }));
    passed('6–8, 11. 선택 날짜 기본값·진료 생성·즉시 달력 반영·상세 및 Post와 공존');
    await page.getByRole('button', { name: '진료 수정', exact: true }).click();
    await page.getByLabel('제목', { exact: true }).fill('변경한 진료');
    await page.getByLabel('시간 (서울)').fill('16:45');
    await page.getByRole('button', { name: '진료 저장', exact: true }).click();
    await visible(details.getByText('변경한 진료', { exact: true }));
    assert.equal(await details.locator('.visit-heading time').textContent(), '16:45');
    passed('9. 진료 제목·시간 수정');
    await page.reload();
    await page.getByRole('button', { name: '달력', exact: true }).click();
    await visible(details.getByText('변경한 진료', { exact: true }));
    await visible(details.getByText(`${token} 첫 기록`, { exact: true }));
    passed('12. 새로고침 후 Post·진료 유지');
    await page.screenshot({ path: `${output}/desktop-calendar.png`, fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.getByRole('button', { name: '진료 수정', exact: true }).click();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({ path: `${output}/mobile-calendar-form.png`, fullPage: true });
    await page.getByRole('button', { name: '취소', exact: true }).click();
    await page.screenshot({ path: `${output}/mobile-calendar.png`, fullPage: true });
    passed('13. 390px 달력·진료 폼 가로 넘침 없음');
    // Calendar Post editing/deletion use the original Post endpoints.
    const firstPost = details.locator('.post').filter({ hasText: `${token} 첫 기록` });
    await firstPost.getByRole('button', { name: '수정', exact: true }).click();
    await firstPost.getByLabel('기록 수정').fill(`${token} 달력 수정`);
    await details.getByRole('button', { name: '저장', exact: true }).click();
    await visible(details.getByText(`${token} 달력 수정`, { exact: true }));
    await details.locator('.post').filter({ hasText: `${token} 달력 수정` }).getByRole('button', { name: '삭제', exact: true }).click();
    await page.getByText(`${token} 달력 수정`, { exact: true }).waitFor({ state: 'hidden' });
    assert.equal(await todayCell.locator('.post-count').textContent(), '● 1');
    passed('날짜별 Post 수정·삭제 및 달력 개수 갱신');
    await page.getByRole('button', { name: '진료 삭제', exact: true }).click();
    await page.getByText('변경한 진료', { exact: true }).waitFor({ state: 'hidden' });
    assert.equal(await todayCell.locator('.visit-marker').count(), 0);
    assert.equal(await todayCell.locator('.post-count').textContent(), '● 1');
    passed('10. 진료 삭제 및 Post 보존');
    await page.getByRole('link', { name: '✚ 복용약', exact: true }).click();
    await page.getByRole('button', { name: '+ 약 추가', exact: true }).click();
    await page.getByLabel('약 이름', { exact: true }).fill('브라우저 검증약');
    await page.getByLabel('복용량', { exact: true }).fill('1정');
    await page.getByRole('button', { name: '+ 복용 시간 추가', exact: true }).click();
    await page.getByRole('button', { name: '저장', exact: true }).click();
    const meds = page.getByRole('region', { name: '오늘의 복용약', exact: true });
    await meds.getByRole('button', { name: '복용 완료', exact: true }).first().click();
    await visible(meds.locator('.med-status.taken'));
    assert.match(await meds.locator('.med-status.taken').textContent(), /\d{2}:\d{2} 복용 완료/);
    await meds.getByRole('button', { name: '건너뜀', exact: true }).nth(1).click();
    await visible(meds.locator('.med-status.skipped'));
    const active = page.getByRole('region', { name: '복용 중인 약', exact: true });
    await active.getByRole('button', { name: '수정', exact: true }).click();
    await page.getByLabel('복용량', { exact: true }).fill('2정');
    await page.getByRole('button', { name: '저장', exact: true }).click();
    await visible(active.getByText('2정', { exact: true }));
    await active.getByRole('button', { name: '복용 중단', exact: true }).click();
    await active.getByRole('button', { name: '중단 확인', exact: true }).click();
    await visible(active.getByText('복용 중인 약이 없어요.', { exact: true }));
    assert.equal(await meds.locator('.med-status.taken').count(), 1);
    assert.equal(await meds.locator('.med-status.skipped').count(), 1);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    passed('14. 약 등록·수정·중단·오늘 복약·복용 완료·건너뜀·실제 시각 보존');
    assert.deepEqual(errors, []);
    passed('브라우저 JavaScript 오류 없음 (America/Los_Angeles 시간대에서 검증)');
    fs.writeFileSync(`${output}/results.json`, JSON.stringify({ results, timezone: 'America/Los_Angeles', viewport: 390 }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
